"""Build supabase/seed_cefr_content.sql from content/cefr/mock-sets.json.

Usage:  python3 scripts/content/build_cefr_seed_sql.py
The generated SQL is safe to run more than once: topics are matched by
(exam, part, title), questions by (topic, text), mock sets by (exam, name).

CEFR part numbers in the database (labels live in src/config/exams.ts):
  1 = Part 1.1  three short questions
  2 = Part 1.2  two pictures + three questions (topic.images, questions in order)
  3 = Part 2    one picture + three questions (topic.images, topic.cue_bullets)
  4 = Part 3    statement (topic.title) + topic.points_for / topic.points_against

Each test in the JSON becomes one CEFR mock set with those four topics, and
every topic also goes into the General Training pools.
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "content" / "cefr" / "mock-sets.json"
TARGET = ROOT / "supabase" / "seed_cefr_content.sql"
PUBLIC = ROOT / "public"


def image(directory: str, img: dict) -> dict:
    url = f"{directory}/{img['file']}"
    if not (PUBLIC / url.lstrip("/")).is_file():
        raise SystemExit(f"Missing picture: public{url}")
    if not img.get("alt"):
        raise SystemExit(f"Picture without alt text: {url}")
    return {"url": url, "alt": img["alt"]}


def build() -> dict:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    directory = data["image_dir"]
    topics: list[dict] = []
    mock_sets: list[dict] = []
    seen: set[tuple[int, str]] = set()

    def add(topic: dict) -> dict:
        key = (topic["part"], topic["title"].strip().lower())
        if key in seen:
            raise SystemExit(f"Two topics with the same title in Part {topic['part']}: {topic['title']}")
        seen.add(key)
        topics.append(topic)
        return {"part": topic["part"], "title": topic["title"]}

    for n, s in enumerate(data["sets"], start=1):
        p11, p12, p2, p3 = s["part1_1"], s["part1_2"], s["part2"], s["part3"]
        assert len(p11["questions"]) == 3 and len(p12["questions"]) == 3, s["name"]
        assert len(p12["images"]) == 2 and len(p2["questions"]) == 3, s["name"]
        assert p3["for"] and p3["against"], s["name"]
        set_topics = [
            add({"part": 1, "title": p11["title"], "questions": p11["questions"]}),
            add({
                "part": 2,
                "title": p12["title"],
                "images": [image(directory, i) for i in p12["images"]],
                "questions": p12["questions"],
            }),
            add({
                "part": 3,
                "title": p2["title"],
                "images": [image(directory, p2["image"])],
                "bullets": p2["questions"],
            }),
            add({"part": 4, "title": p3["statement"], "for": p3["for"], "against": p3["against"]}),
        ]
        mock_sets.append({"name": s["name"], "sort_order": n, "topics": set_topics})

    return {"topics": topics, "mock_sets": mock_sets}


SQL = """-- Generated by scripts/content/build_cefr_seed_sql.py from content/cefr/mock-sets.json.
-- Do not edit by hand: change the JSON and run the script again.
-- Needs migration 20261120000100_cefr_multilevel_format.sql. Safe to run more than once.
-- {topics} CEFR topics, {questions} questions, {mocks} mock sets.

do $seed$
declare
  d jsonb := $json${payload}$json$::jsonb;
  t jsonb;
  m record;
  mt record;
  q record;
  tid uuid;
  ms uuid;
begin
  -- Topics and their questions
  for t in select * from jsonb_array_elements(d->'topics') loop
    insert into public.topics (exam, part, title, cue_bullets, images, points_for, points_against)
    values (
      'cefr', (t->>'part')::smallint, t->>'title',
      coalesce(array(select jsonb_array_elements_text(t->'bullets')), '{{}}'),
      coalesce(t->'images', '[]'::jsonb),
      coalesce(array(select jsonb_array_elements_text(t->'for')), '{{}}'),
      coalesce(array(select jsonb_array_elements_text(t->'against')), '{{}}')
    )
    on conflict (exam, part, lower(btrim(title))) do update set
      cue_bullets = excluded.cue_bullets,
      images = excluded.images,
      points_for = excluded.points_for,
      points_against = excluded.points_against
    returning id into tid;

    for q in select value as text, ordinality as n
             from jsonb_array_elements_text(coalesce(t->'questions', '[]'::jsonb)) with ordinality loop
      insert into public.questions (topic_id, text, sort_order) values (tid, q.text, q.n)
      on conflict (topic_id, lower(btrim(text))) do nothing;
    end loop;
  end loop;

  -- Mock sets: exactly the four topics of each test, in exam order
  for m in select value as s from jsonb_array_elements(d->'mock_sets') loop
    insert into public.mock_sets (exam, name, sort_order)
    values ('cefr', m.s->>'name', (m.s->>'sort_order')::int)
    on conflict (exam, lower(btrim(name))) do update set sort_order = excluded.sort_order
    returning id into ms;

    delete from public.mock_set_topics where mock_set_id = ms;
    for mt in select value as x, ordinality as n from jsonb_array_elements(m.s->'topics') with ordinality loop
      select id into tid from public.topics
      where exam = 'cefr' and part = (mt.x->>'part')::smallint and lower(btrim(title)) = lower(btrim(mt.x->>'title'));
      insert into public.mock_set_topics (mock_set_id, topic_id, part, sort_order)
      values (ms, tid, (mt.x->>'part')::smallint, mt.n);
    end loop;
  end loop;
end
$seed$;
"""


def main() -> None:
    payload = build()
    text = json.dumps(payload, ensure_ascii=False)
    assert "$json$" not in text
    questions = sum(len(t.get("questions", [])) for t in payload["topics"])
    TARGET.write_text(
        SQL.format(
            payload=text,
            topics=len(payload["topics"]),
            questions=questions,
            mocks=len(payload["mock_sets"]),
        ),
        encoding="utf-8",
    )
    print(f"Wrote {TARGET.relative_to(ROOT)}: {len(payload['topics'])} topics, {questions} questions, {len(payload['mock_sets'])} mock sets")


if __name__ == "__main__":
    main()
