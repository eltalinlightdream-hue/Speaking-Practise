"""Build supabase/seed_content.sql from content/ielts/mock-sets.json.

Usage:  python3 scripts/content/build_seed_sql.py
The generated SQL is safe to run more than once: topics are matched by
(exam, part, title), questions by (topic, text), mock sets by (exam, name).

Rules (decided with the owner):
- each complete set becomes one IELTS mock set (Part 1 topic, Part 2 cue card, Part 3 topic);
- incomplete sets (no cue card, e.g. 20-25) are NOT mock sets, but their Part 1
  and Part 3 questions are still loaded for General Training;
- Part 1 topics with the same title are merged (questions de-duplicated).
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "content" / "ielts" / "mock-sets.json"
OUT = ROOT / "supabase" / "seed_content.sql"

data = json.loads(SRC.read_text(encoding="utf-8"))
payload = json.dumps({"mock_sets": data["mock_sets"]}, ensure_ascii=False)
assert "$json$" not in payload

CEFR_PLACEHOLDERS = {
    "topics": [
        {"part": 1, "title": "Placeholder: About you", "questions": ["What is your name?", "Where are you from?", "What do you do in your free time?"]},
        {"part": 2, "title": "Placeholder: Describe a picture", "bullets": ["What you can see", "What the people are doing"], "explain": "and explain how the picture makes you feel"},
        {"part": 3, "title": "Placeholder: Technology", "questions": ["How has technology changed the way people study?", "Is it good for children to use phones?"]},
    ]
}
cefr = json.dumps(CEFR_PLACEHOLDERS, ensure_ascii=False)

sql = f"""-- GENERATED by scripts/content/build_seed_sql.py. Do not edit by hand.
-- Loads the IELTS speaking sets and CEFR placeholder content. Safe to re-run.

do $seed$
declare
  d jsonb := $json${payload}$json$::jsonb;
  c jsonb := $json${cefr}$json$::jsonb;
  s jsonb;
  t jsonb;
  q text;
  p1 uuid;
  p2 uuid;
  p3 uuid;
  tid uuid;
  ms uuid;
  next_order int;
begin
  for s in select * from jsonb_array_elements(d->'mock_sets') loop
    -- Part 1 topic (merged by title)
    insert into public.topics (exam, part, title)
    values ('ielts', 1, s->'part1'->>'title')
    on conflict (exam, part, lower(btrim(title))) do update set title = public.topics.title
    returning id into p1;

    for q in select jsonb_array_elements_text(s->'part1'->'questions') loop
      select coalesce(max(sort_order), 0) + 1 into next_order from public.questions where topic_id = p1;
      insert into public.questions (topic_id, text, sort_order) values (p1, q, next_order)
      on conflict (topic_id, lower(btrim(text))) do nothing;
    end loop;

    -- Part 2 cue card (only complete sets have one)
    p2 := null;
    if jsonb_typeof(s->'part2') = 'object' then
      insert into public.topics (exam, part, title, cue_bullets, cue_explain)
      values (
        'ielts', 2, s->'part2'->>'title',
        array(select jsonb_array_elements_text(s->'part2'->'bullets')),
        s->'part2'->>'explain'
      )
      on conflict (exam, part, lower(btrim(title))) do update
        set cue_bullets = excluded.cue_bullets, cue_explain = excluded.cue_explain
      returning id into p2;
    end if;

    -- Part 3 topic, linked to the cue card
    insert into public.topics (exam, part, title, related_topic_id)
    values ('ielts', 3, s->'part3'->>'title', p2)
    on conflict (exam, part, lower(btrim(title))) do update
      set related_topic_id = coalesce(excluded.related_topic_id, public.topics.related_topic_id)
    returning id into p3;

    for q in select jsonb_array_elements_text(s->'part3'->'questions') loop
      select coalesce(max(sort_order), 0) + 1 into next_order from public.questions where topic_id = p3;
      insert into public.questions (topic_id, text, sort_order) values (p3, q, next_order)
      on conflict (topic_id, lower(btrim(text))) do nothing;
    end loop;

    -- Mock set: complete sets only
    if (s->>'complete')::boolean and p2 is not null then
      insert into public.mock_sets (exam, name, sort_order)
      values ('ielts', s->>'name', (s->>'set_number')::int)
      on conflict (exam, lower(btrim(name))) do update set sort_order = excluded.sort_order
      returning id into ms;

      delete from public.mock_set_topics where mock_set_id = ms;
      insert into public.mock_set_topics (mock_set_id, topic_id, part, sort_order) values
        (ms, p1, 1, 1), (ms, p2, 2, 1), (ms, p3, 3, 1);
    end if;
  end loop;

  -- CEFR placeholders (until the real format is added)
  for t in select * from jsonb_array_elements(c->'topics') loop
    insert into public.topics (exam, part, title, is_placeholder, cue_bullets, cue_explain)
    values (
      'cefr', (t->>'part')::smallint, t->>'title', true,
      coalesce(array(select jsonb_array_elements_text(t->'bullets')), '{{}}'),
      t->>'explain'
    )
    on conflict (exam, part, lower(btrim(title))) do update set is_placeholder = true
    returning id into tid;

    for q in select jsonb_array_elements_text(coalesce(t->'questions', '[]'::jsonb)) loop
      select coalesce(max(sort_order), 0) + 1 into next_order from public.questions where topic_id = tid;
      insert into public.questions (topic_id, text, sort_order) values (tid, q, next_order)
      on conflict (topic_id, lower(btrim(text))) do nothing;
    end loop;
  end loop;
end
$seed$;
"""

OUT.write_text(sql, encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)} ({len(sql)} bytes)")
